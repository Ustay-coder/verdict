#!/usr/bin/env bash
# Prepare Codex CLI inside a cloud / CI container using ChatGPT (OAuth) auth — no OPENAI_API_KEY.
#
# Auth comes from ONE of:
#   1. CODEX_AUTH_JSON  — the full contents of ~/.codex/auth.json from a machine where you ran `codex login`
#                        (store it as an environment secret; it holds the OAuth refresh token, treat it like a password)
#   2. CODEX_AUTH_JSON_B64 — same, base64-encoded (safer for secret stores that mangle JSON)
#   3. nothing          — falls back to `codex login --device-auth` (prints a URL + code to approve on any device)
#
# Network policy must allow: auth.openai.com, chatgpt.com, api.openai.com
set -euo pipefail
export NODE_USE_ENV_PROXY=1   # Node's fetch must honour the container's HTTPS_PROXY (Jev / Clef calls, tests)

CODEX_VERSION="${CODEX_VERSION:-latest}"
CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"

command -v codex >/dev/null 2>&1 || npm install -g "@openai/codex@$CODEX_VERSION" >/dev/null
echo "▶ codex $(codex --version)"
mkdir -p "$CODEX_HOME"

cat > "$CODEX_HOME/config.toml" <<TOML
# Generated by scripts/codex-cloud.sh — headless defaults. ChatGPT (OAuth) auth lives in auth.json; leave `model`
# unset so Codex picks the model the ChatGPT plan supports (explicit "gpt-5-codex" is rejected on ChatGPT accounts).
approval_policy = "never"
sandbox_mode = "workspace-write"

[projects."$REPO_DIR"]
trust_level = "trusted"
TOML

if [ -n "${CODEX_AUTH_JSON_B64:-}" ]; then
  printf '%s' "$CODEX_AUTH_JSON_B64" | base64 -d > "$CODEX_HOME/auth.json"
elif [ -n "${CODEX_AUTH_JSON:-}" ]; then
  printf '%s' "$CODEX_AUTH_JSON" > "$CODEX_HOME/auth.json"
fi
[ -f "$CODEX_HOME/auth.json" ] && chmod 600 "$CODEX_HOME/auth.json"

if [ -n "${OPENAI_API_KEY:-}" ]; then
  echo "⚠ OPENAI_API_KEY is set; unsetting it for Codex so usage stays on the ChatGPT subscription"
  unset OPENAI_API_KEY
fi

for host in auth.openai.com chatgpt.com; do
  code=$(curl -sS -o /dev/null -m 10 -w "%{http_code}" "https://$host/" 2>/dev/null || echo 000)
  [ "$code" = "000" ] && echo "✖ cannot reach https://$host — add it to the environment's allowed domains" && exit 2
done

if codex login status 2>/dev/null | grep -qi "logged in"; then
  echo "✔ $(codex login status 2>/dev/null | head -1)"
else
  echo "▶ no stored credentials; starting device-code login (approve the printed code on any device)"
  codex login --device-auth
fi
echo "✔ ready: run  codex exec \"<task>\" < /dev/null  from $REPO_DIR   (close stdin in non-interactive runs or Codex waits for input)"
